/* ═══════════════════════════════════════════════════
   SARKARI RESULT TOOLS — Robots.txt & XML Sitemap Generator
   ═══════════════════════════════════════════════════ */

document.addEventListener('DOMContentLoaded', () => {
  // Tabs
  const mainToolTabs = document.querySelectorAll('#mainToolTabs .tool-tab');
  const tabRobotsContent = document.getElementById('tabRobotsContent');
  const tabSitemapContent = document.getElementById('tabSitemapContent');

  mainToolTabs.forEach(tab => {
    tab.addEventListener('click', () => {
      mainToolTabs.forEach(t => t.classList.remove('active'));
      tab.classList.add('active');
      const target = tab.dataset.tab;
      tabRobotsContent.style.display = target === 'tabRobots' ? 'block' : 'none';
      tabSitemapContent.style.display = target === 'tabSitemap' ? 'block' : 'none';
    });
  });

  // ═══════════════════ ROBOTS.TXT LOGIC ═══════════════════
  const robotsUserAgent = document.getElementById('robotsUserAgent');
  const robotsCrawlDelay = document.getElementById('robotsCrawlDelay');
  const robotsSitemapUrl = document.getElementById('robotsSitemapUrl');
  const robotsRulesContainer = document.getElementById('robotsRulesContainer');
  const btnAddRobotsRule = document.getElementById('btnAddRobotsRule');
  const robotsOutput = document.getElementById('robotsOutput');
  const btnCopyRobots = document.getElementById('btnCopyRobots');
  const btnDownloadRobots = document.getElementById('btnDownloadRobots');

  const testUrlInput = document.getElementById('testUrlInput');
  const btnTestUrl = document.getElementById('btnTestUrl');
  const testUrlResult = document.getElementById('testUrlResult');

  // Presets
  const btnPresetWp = document.getElementById('btnPresetWp');
  const btnPresetShopify = document.getElementById('btnPresetShopify');
  const btnPresetStatic = document.getElementById('btnPresetStatic');
  const btnPresetAllowAll = document.getElementById('btnPresetAllowAll');
  const btnPresetBlockAll = document.getElementById('btnPresetBlockAll');

  let rules = [
    { type: 'Disallow', path: '/admin/' },
    { type: 'Disallow', path: '/private/' },
    { type: 'Disallow', path: '/*.pdf$' },
    { type: 'Allow', path: '/public/' }
  ];

  function renderRules() {
    robotsRulesContainer.innerHTML = '';
    rules.forEach((rule, idx) => {
      const row = document.createElement('div');
      row.style.cssText = 'display: flex; gap: 8px; align-items: center;';
      row.innerHTML = `
        <select class="form-input rule-type" data-idx="${idx}" style="width: 120px; font-weight: 600; color: ${rule.type === 'Disallow' ? '#dc2626' : '#16a34a'};">
          <option value="Disallow" ${rule.type === 'Disallow' ? 'selected' : ''}>Disallow</option>
          <option value="Allow" ${rule.type === 'Allow' ? 'selected' : ''}>Allow</option>
        </select>
        <input type="text" class="form-input rule-path" data-idx="${idx}" value="${escapeHtml(rule.path)}" placeholder="/path/" style="flex: 1; font-family: monospace; font-size: 13px;">
        <button type="button" class="btn btn-outline btn-del-rule" data-idx="${idx}" style="color: #dc2626; padding: 4px 10px; font-size: 12px;" title="Delete Rule">✕</button>
      `;
      robotsRulesContainer.appendChild(row);
    });

    // Attach listeners
    robotsRulesContainer.querySelectorAll('.rule-type').forEach(sel => {
      sel.addEventListener('change', (e) => {
        const i = parseInt(e.target.dataset.idx, 10);
        rules[i].type = e.target.value;
        renderRules();
        generateRobotsTxt();
      });
    });

    robotsRulesContainer.querySelectorAll('.rule-path').forEach(inp => {
      inp.addEventListener('input', (e) => {
        const i = parseInt(e.target.dataset.idx, 10);
        rules[i].path = e.target.value;
        generateRobotsTxt();
      });
    });

    robotsRulesContainer.querySelectorAll('.btn-del-rule').forEach(btn => {
      btn.addEventListener('click', (e) => {
        const i = parseInt(e.target.dataset.idx, 10);
        rules.splice(i, 1);
        renderRules();
        generateRobotsTxt();
      });
    });
  }

  btnAddRobotsRule.addEventListener('click', () => {
    rules.push({ type: 'Disallow', path: '/new-folder/' });
    renderRules();
    generateRobotsTxt();
  });

  [robotsUserAgent, robotsCrawlDelay, robotsSitemapUrl].forEach(el => {
    el.addEventListener('input', generateRobotsTxt);
  });

  function generateRobotsTxt() {
    const ua = robotsUserAgent.value;
    const delay = parseInt(robotsCrawlDelay.value, 10);
    const sitemap = robotsSitemapUrl.value.trim();

    let out = `# Robots.txt generated by Sarkari Result Tools (sarkaritools.in)\n`;
    out += `User-agent: ${ua}\n`;

    if (delay > 0) {
      out += `Crawl-delay: ${delay}\n`;
    }

    if (rules.length === 0) {
      out += `Disallow:\n`;
    } else {
      rules.forEach(r => {
        if (r.path.trim()) {
          out += `${r.type}: ${r.path.trim()}\n`;
        }
      });
    }

    if (sitemap) {
      out += `\n# Sitemap Directive\nSitemap: ${sitemap}\n`;
    }

    robotsOutput.textContent = out;
  }

  // Presets
  btnPresetWp.addEventListener('click', () => {
    rules = [
      { type: 'Disallow', path: '/wp-admin/' },
      { type: 'Allow', path: '/wp-admin/admin-ajax.php' },
      { type: 'Disallow', path: '/wp-includes/' },
      { type: 'Disallow', path: '/readme.html' },
      { type: 'Disallow', path: '/*?s=*' }
    ];
    robotsSitemapUrl.value = 'https://example.com/sitemap_index.xml';
    renderRules();
    generateRobotsTxt();
  });

  btnPresetShopify.addEventListener('click', () => {
    rules = [
      { type: 'Disallow', path: '/admin' },
      { type: 'Disallow', path: '/cart' },
      { type: 'Disallow', path: '/orders' },
      { type: 'Disallow', path: '/checkout' },
      { type: 'Disallow', path: '/*?*preview_theme_id*' }
    ];
    robotsSitemapUrl.value = 'https://example.com/sitemap.xml';
    renderRules();
    generateRobotsTxt();
  });

  btnPresetStatic.addEventListener('click', () => {
    rules = [
      { type: 'Disallow', path: '/cgi-bin/' },
      { type: 'Disallow', path: '/private/' },
      { type: 'Disallow', path: '/tmp/' }
    ];
    robotsSitemapUrl.value = 'https://sarkaritools.in/sitemap.xml';
    renderRules();
    generateRobotsTxt();
  });

  btnPresetAllowAll.addEventListener('click', () => {
    rules = [{ type: 'Disallow', path: '' }];
    renderRules();
    generateRobotsTxt();
  });

  btnPresetBlockAll.addEventListener('click', () => {
    rules = [{ type: 'Disallow', path: '/' }];
    renderRules();
    generateRobotsTxt();
  });

  // URL Crawl Tester
  btnTestUrl.addEventListener('click', () => {
    const testPath = (testUrlInput.value || '').trim();
    if (!testPath) {
      alert('Please enter a relative path to test (e.g. /wp-admin/test.php)');
      testUrlInput.focus();
      return;
    }

    testUrlResult.style.display = 'block';

    // Top-to-bottom rule match
    let status = 'ALLOWED';
    let matchedRule = null;

    for (const r of rules) {
      if (!r.path) continue;
      // Simple prefix / regex pattern match
      const pattern = r.path.replace(/\*/g, '.*').replace(/\$/g, '$');
      const reg = new RegExp('^' + pattern);
      if (reg.test(testPath) || testPath.startsWith(r.path)) {
        status = r.type === 'Disallow' ? 'BLOCKED' : 'ALLOWED';
        matchedRule = `${r.type}: ${r.path}`;
        break;
      }
    }

    if (status === 'ALLOWED') {
      testUrlResult.innerHTML = `<span style="color: #16a34a;">✓ CRAWL ALLOWED</span> — Search engines can access <code>${escapeHtml(testPath)}</code> ${matchedRule ? `(Matched: ${matchedRule})` : '(No blocking rules)'}`;
    } else {
      testUrlResult.innerHTML = `<span style="color: #dc2626;">✗ CRAWL BLOCKED</span> — Search engines are forbidden from indexing <code>${escapeHtml(testPath)}</code> (Matched: ${matchedRule})`;
    }
  });

  // Copy robots.txt
  btnCopyRobots.addEventListener('click', () => {
    navigator.clipboard.writeText(robotsOutput.textContent).then(() => {
      const orig = btnCopyRobots.textContent;
      btnCopyRobots.textContent = '✓ Copied!';
      setTimeout(() => { btnCopyRobots.textContent = orig; }, 2000);
    });
  });

  // Download robots.txt
  btnDownloadRobots.addEventListener('click', () => {
    const blob = new Blob([robotsOutput.textContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'robots.txt';
    a.click();
    URL.revokeObjectURL(url);
  });

  // ═══════════════════ XML SITEMAP LOGIC ═══════════════════
  const sitemapBaseUrl = document.getElementById('sitemapBaseUrl');
  const sitemapDefaultFreq = document.getElementById('sitemapDefaultFreq');
  const sitemapBulkUrls = document.getElementById('sitemapBulkUrls');
  const btnParseBulkUrls = document.getElementById('btnParseBulkUrls');
  const sitemapUrlCount = document.getElementById('sitemapUrlCount');
  const sitemapOutput = document.getElementById('sitemapOutput');
  const btnCopySitemap = document.getElementById('btnCopySitemap');
  const btnDownloadSitemap = document.getElementById('btnDownloadSitemap');

  let sitemapItems = [
    { loc: 'https://sarkaritools.in/', priority: '1.0', changefreq: 'daily' },
    { loc: 'https://sarkaritools.in/tools/image-resizer.html', priority: '0.9', changefreq: 'weekly' },
    { loc: 'https://sarkaritools.in/tools/age-calculator.html', priority: '0.9', changefreq: 'weekly' },
    { loc: 'https://sarkaritools.in/tools/typing-test.html', priority: '0.9', changefreq: 'weekly' },
    { loc: 'https://sarkaritools.in/tools/resume-maker.html', priority: '0.8', changefreq: 'monthly' }
  ];

  function buildXml() {
    const today = new Date().toISOString().split('T')[0];
    let xml = `<?xml version="1.0" encoding="UTF-8"?>\n`;
    xml += `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n`;

    sitemapItems.forEach(item => {
      xml += `  <url>\n`;
      xml += `    <loc>${escapeXml(item.loc)}</loc>\n`;
      xml += `    <lastmod>${today}</lastmod>\n`;
      xml += `    <changefreq>${item.changefreq || 'weekly'}</changefreq>\n`;
      xml += `    <priority>${item.priority || '0.8'}</priority>\n`;
      xml += `  </url>\n`;
    });

    xml += `</urlset>`;

    sitemapUrlCount.textContent = sitemapItems.length;
    sitemapOutput.textContent = xml;
  }

  btnParseBulkUrls.addEventListener('click', () => {
    const raw = sitemapBulkUrls.value.trim();
    if (!raw) {
      alert('Please paste at least one URL');
      return;
    }

    const lines = raw.split(/\r?\n/).map(l => l.trim()).filter(Boolean);
    const freq = sitemapDefaultFreq.value;

    sitemapItems = lines.map((url, idx) => ({
      loc: url,
      priority: idx === 0 ? '1.0' : (idx < 5 ? '0.9' : '0.8'),
      changefreq: freq
    }));

    buildXml();
  });

  btnCopySitemap.addEventListener('click', () => {
    navigator.clipboard.writeText(sitemapOutput.textContent).then(() => {
      const orig = btnCopySitemap.textContent;
      btnCopySitemap.textContent = '✓ Copied XML!';
      setTimeout(() => { btnCopySitemap.textContent = orig; }, 2000);
    });
  });

  btnDownloadSitemap.addEventListener('click', () => {
    const blob = new Blob([sitemapOutput.textContent], { type: 'application/xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'sitemap.xml';
    a.click();
    URL.revokeObjectURL(url);
  });

  function escapeXml(unsafe) {
    return (unsafe || '').replace(/[<>&'"]/g, c => {
      switch (c) {
        case '<': return '&lt;';
        case '>': return '&gt;';
        case '&': return '&amp;';
        case '\'': return '&apos;';
        case '"': return '&quot;';
      }
    });
  }

  function escapeHtml(str) {
    return (str || '').replace(/[&<>"']/g, m => ({
      '&': '&amp;',
      '<': '&lt;',
      '>': '&gt;',
      '"': '&quot;',
      "'": '&#039;'
    })[m]);
  }

  // Initialize
  renderRules();
  generateRobotsTxt();
  buildXml();

});
